"""Build every chart, save PNGs to figures/ and write the takeaways."""

from __future__ import annotations

import json
import time
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np

from . import data, features, plots


def _jsonable(v):
    if isinstance(v, (np.floating, float)):
        return round(float(v), 4)
    if isinstance(v, (np.integer,)):
        return int(v)
    if isinstance(v, tuple):
        return [_jsonable(x) for x in v]
    return v


def build_report(df, out_dir: str | Path = "figures", verbose: bool = True) -> dict:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    plots.set_style()
    df = features.add_features(df)
    results = {}
    lines = ["# Chart takeaways", "", "Generated by `python -m energy_eda report`.", ""]
    for name, fn in plots.CHARTS:
        t0 = time.time()
        fig, takeaway, nums = fn(df)
        path = out / f"{name}.png"
        fig.savefig(path)
        plt.close(fig)
        results[name] = {"takeaway": takeaway, "numbers": {k: _jsonable(v) for k, v in nums.items()}}
        lines += [f"## {name}", "", f"![{name}]({name}.png)", "", takeaway, ""]
        if verbose:
            print(f"[{time.time() - t0:4.1f}s] {path}\n        {takeaway}")
    (out / "takeaways.md").write_text("\n".join(lines))
    (out / "results.json").write_text(json.dumps(results, indent=2))
    return results


def run(source: str = "sample", duckdb_path=None, opsd_csv=None, out_dir="figures") -> dict:
    df = data.load(source, duckdb_path, opsd_csv)
    print(f"Loaded {len(df):,} hourly rows from '{source}' "
          f"({df.index.min():%Y-%m-%d %H:%M} to {df.index.max():%Y-%m-%d %H:%M} UTC)")
    return build_report(df, out_dir)
